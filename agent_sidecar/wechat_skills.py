def wechat_skill_catalog() -> List[Dict[str, Any]]:
    """Return defensive copies so callers cannot mutate the immutable catalog."""
    return deepcopy(_CATALOG)


def wechat_skill_by_id(skill_id: str) -> Optional[Dict[str, Any]]:
    for manifest in _CATALOG:
        if manifest["skill_id"] == skill_id:
            return deepcopy(manifest)
    return None


def wechat_catalog_payload(installed_ids: Optional[Iterable[str]] = None) -> Dict[str, Any]:
    installed = set(installed_ids or [])
    skills = wechat_skill_catalog()
    for manifest in skills:
        manifest["installed"] = manifest["skill_id"] in installed
    categories: Dict[str, int] = {}
    for manifest in skills:
        categories[manifest["category"]] = categories.get(manifest["category"], 0) + 1
    return {
        "schema": CATALOG_SCHEMA,
        "version": CATALOG_VERSION,
        "as_of": CATALOG_VERSION.replace(".", "-"),
        "count": len(skills),
        "installed_count": sum(1 for item in skills if item["installed"]),
        "categories": [{"name": name, "count": count} for name, count in categories.items()],
        "skills": skills,
    }
